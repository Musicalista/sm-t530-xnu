static inline void fb_draw_char(uint32_t x, uint32_t y, char c, uint16_t color, uint32_t scale) {
    if (c < 32 || c > 126) c = ' ';
    const uint8_t *glyph = font5x7[c - 32];
    for (uint32_t col = 0; col < 5; col++) {
        uint8_t line = glyph[col];
        for (uint32_t row = 0; row < 7; row++) {
            if (line & (1 << row)) {
                for (uint32_t dy = 0; dy < scale; dy++) {
                    for (uint32_t dx = 0; dx < scale; dx++) {
                        uint32_t px = x + col * scale + dx;
                        uint32_t py = y + row * scale + dy;
                        if (px < FB_WIDTH && py < FB_HEIGHT) {
                            FB_BASE[py * FB_WIDTH + px] = color;
                        }
                    }
                }
            }
        }
    }
}

static inline void fb_draw_text(uint32_t x, uint32_t y, const char *str, uint16_t color, uint32_t scale) {
    uint32_t cur_x = x;
    while (*str) {
        if (*str == '\n') {
            y += (8 * scale);
            cur_x = x;
        } else {
            fb_draw_char(cur_x, y, *str, color, scale);
            cur_x += (6 * scale);
        }
        str++;
    }
}

