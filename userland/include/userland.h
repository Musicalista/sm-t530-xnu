/* Early Serial Output via Qualcomm UARTDM */
static inline void klog_putc(char c) {
    volatile uint32_t *sr   = (volatile uint32_t *)MSM_UARTDM_SR;
    volatile uint32_t *tx   = (volatile uint32_t *)MSM_UARTDM_TF;
    volatile uint32_t *ncft = (volatile uint32_t *)MSM_UARTDM_NCF_TX;

    while (!(*sr & (1 << 3))) {}
    *ncft = 1;
    *tx = (uint32_t)c;
}

static inline void klog(const char *msg) {
    while (*msg) {
        if (*msg == '\n') klog_putc('\r');
        klog_putc(*msg++);
    }
}

/* Graphics Drawing Primitives */
static inline void fb_fill(uint16_t color) {
    for (uint32_t i = 0; i < FB_WIDTH * FB_HEIGHT; i++) {
        FB_BASE[i] = color;
    }
}

static inline void fb_draw_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint16_t color) {
    for (uint32_t j = y; j < y + h && j < FB_HEIGHT; j++) {
        for (uint32_t i = x; i < x + w && i < FB_WIDTH; i++) {
            FB_BASE[j * FB_WIDTH + i] = color;
        }
    }
}

static inline void fb_draw_rounded_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t r, uint16_t color) {
    for (uint32_t j = y; j < y + h && j < FB_HEIGHT; j++) {
        for (uint32_t i = x; i < x + w && i < FB_WIDTH; i++) {
            /* Approximate rounded corners */
            uint32_t dx = (i < x + r) ? (x + r - i) : (i > x + w - r) ? (i - (x + w - r)) : 0;
            uint32_t dy = (j < y + r) ? (y + r - j) : (j > y + h - r) ? (j - (y + h - r)) : 0;
            if (dx * dx + dy * dy <= r * r) {
                FB_BASE[j * FB_WIDTH + i] = color;
            }
        }
    }
}

